#!/usr/bin/env bash
set -euo pipefail

# Applies GyroTube Android customizations after `cargo tauri android init`.
# Safe to run repeatedly (idempotent).

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GEN_MAIN="${SCRIPT_DIR}/../src-tauri/gen/android/app/src/main"
MANIFEST="${GEN_MAIN}/AndroidManifest.xml"

if [[ ! -f "${MANIFEST}" ]]; then
  echo "Error: ${MANIFEST} not found. Run 'cargo tauri android init' inside apps/tauri first." >&2
  exit 1
fi

mkdir -p "${GEN_MAIN}/res/xml"
cp "${SCRIPT_DIR}/res/xml/network_security_config.xml" "${GEN_MAIN}/res/xml/network_security_config.xml"

# Copy GyroTube launcher icons (replaces default Tauri icons generated by `tauri android init`)
ICONS_SRC="${SCRIPT_DIR}/../src-tauri/icons/android"
for density in mipmap-mdpi mipmap-hdpi mipmap-xhdpi mipmap-xxhdpi mipmap-xxxhdpi; do
  if [[ -d "${ICONS_SRC}/${density}" ]]; then
    mkdir -p "${GEN_MAIN}/res/${density}"
    cp -f "${ICONS_SRC}/${density}/"*.png "${GEN_MAIN}/res/${density}/"
  fi
done
mkdir -p "${GEN_MAIN}/res/mipmap-anydpi-v26" "${GEN_MAIN}/res/values"
cp -f "${SCRIPT_DIR}/res/mipmap-anydpi-v26/ic_launcher.xml" "${GEN_MAIN}/res/mipmap-anydpi-v26/ic_launcher.xml"
cp -f "${SCRIPT_DIR}/res/mipmap-anydpi-v26/ic_launcher_round.xml" "${GEN_MAIN}/res/mipmap-anydpi-v26/ic_launcher_round.xml"
cp -f "${SCRIPT_DIR}/res/values/ic_launcher_background.xml" "${GEN_MAIN}/res/values/ic_launcher_background.xml"

KOTLIN_DEST="${GEN_MAIN}/java/com/github/gyrotube/GyroTube"
mkdir -p "${KOTLIN_DEST}"
cp "${SCRIPT_DIR}/kotlin/com/github/gyrotube/GyroTube/PlaybackForegroundService.kt" \
   "${KOTLIN_DEST}/PlaybackForegroundService.kt"
# Safe-area aware MainActivity (status bar / nav bar / keyboard insets)
cp "${SCRIPT_DIR}/kotlin/com/github/gyrotube/GyroTube/MainActivity.kt" \
   "${KOTLIN_DEST}/MainActivity.kt"

python3 - "${MANIFEST}" <<'PY'
import sys
from pathlib import Path

path = Path(sys.argv[1])
text = path.read_text(encoding="utf-8")

permissions = [
    "android.permission.INTERNET",
    "android.permission.ACCESS_NETWORK_STATE",
    "android.permission.WAKE_LOCK",
    "android.permission.FOREGROUND_SERVICE",
    "android.permission.FOREGROUND_SERVICE_MEDIA_PLAYBACK",
    "android.permission.POST_NOTIFICATIONS",
]

for perm in permissions:
    tag = f'<uses-permission android:name="{perm}" />'
    if perm not in text:
        text = text.replace("<application", f"    {tag}\n    <application", 1)

if "android:networkSecurityConfig" not in text:
    text = text.replace(
        "<application",
        '<application\n        android:networkSecurityConfig="@xml/network_security_config"',
        1,
    )

if "android:roundIcon" not in text:
    text = text.replace(
        'android:icon="@mipmap/ic_launcher"',
        'android:icon="@mipmap/ic_launcher"\n        android:roundIcon="@mipmap/ic_launcher_round"',
        1,
    )

service_decl = (
    '        <service\n'
    '            android:name=".PlaybackForegroundService"\n'
    '            android:exported="false"\n'
    '            android:foregroundServiceType="mediaPlayback" />\n'
)
if "PlaybackForegroundService" not in text:
    text = text.replace("</application>", f"{service_decl}    </application>", 1)

deep_link_filter = (
    '            <intent-filter>\n'
    '                <action android:name="android.intent.action.VIEW" />\n'
    '                <category android:name="android.intent.category.DEFAULT" />\n'
    '                <category android:name="android.intent.category.BROWSABLE" />\n'
    '                <data android:scheme="gyrotube" android:host="spin" />\n'
    '            </intent-filter>\n'
)
if 'android:scheme="gyrotube"' not in text:
    text = text.replace("</activity>", f"{deep_link_filter}        </activity>", 1)

path.write_text(text, encoding="utf-8")
print("Applied GyroTube Android manifest & foreground service configuration.")
PY

BUILD_GRADLE="${SCRIPT_DIR}/../src-tauri/gen/android/app/build.gradle.kts"
if [[ -f "${BUILD_GRADLE}" ]]; then
  python3 - "${BUILD_GRADLE}" <<'PY'
import sys
from pathlib import Path

path = Path(sys.argv[1])
text = path.read_text(encoding="utf-8")
updated = (
    text.replace("JavaVersion.VERSION_1_8", "JavaVersion.VERSION_17")
        .replace("JvmTarget.JVM_1_8", "JvmTarget.JVM_17")
)
if updated != text:
    path.write_text(updated, encoding="utf-8")
    print("Updated Android app/build.gradle.kts to Java/Kotlin target 17.")
PY
fi
